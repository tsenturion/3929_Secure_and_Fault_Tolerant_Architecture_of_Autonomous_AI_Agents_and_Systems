class RunConflict(ValueError):
    pass


class RunStore:
    def __init__(
        self,
        path: Path,
        policy_path: Path = DEFAULT_POLICY_PATH,
        *,
        approval_seconds: int = DEFAULT_APPROVAL_SECONDS,
        clock: Callable[[], datetime] | None = None,
        postgres: PostgresDatabase | None = None,
    ):
        if postgres is None:
            path.parent.mkdir(parents=True, exist_ok=True)
        self.path = path
        self.postgres = postgres
        self.policy_path = policy_path
        self.approval_period = timedelta(seconds=approval_seconds)
        self.clock = clock if clock is not None else lambda: datetime.now(UTC)
        self.cases = CaseStore(self.connection, self.clock)
        with self.connection() as db:
            if postgres is not None:
                begin_write(db)
            incident_key = "INTEGER GENERATED BY DEFAULT AS IDENTITY" if postgres else "INTEGER"
            db.executescript(f"""
                CREATE TABLE IF NOT EXISTS runs (
                    id TEXT PRIMARY KEY,
                    scenario_id TEXT NOT NULL,
                    mode TEXT NOT NULL,
                    status TEXT NOT NULL,
                    started_at TEXT NOT NULL,
                    payload TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS runs_scenario
                    ON runs (scenario_id, mode, started_at DESC);
                CREATE TABLE IF NOT EXISTS support_cards (
                    run_id TEXT PRIMARY KEY REFERENCES runs(id),
                    description TEXT NOT NULL,
                    customer_email TEXT
                );
                CREATE TABLE IF NOT EXISTS tool_calls (
                    run_id TEXT NOT NULL,
                    scenario_id TEXT NOT NULL,
                    service TEXT NOT NULL,
                    operator TEXT NOT NULL,
                    action TEXT NOT NULL,
                    requested_at TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS tool_calls_run ON tool_calls (run_id);
                CREATE INDEX IF NOT EXISTS tool_calls_age ON tool_calls (requested_at);
                CREATE TABLE IF NOT EXISTS incidents (
                    id {incident_key} PRIMARY KEY,
                    run_id TEXT NOT NULL UNIQUE REFERENCES runs(id),
                    scenario_id TEXT NOT NULL UNIQUE,
                    priority TEXT NOT NULL,
                    queue TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    publication TEXT NOT NULL DEFAULT '{{}}'
                );
                CREATE TABLE IF NOT EXISTS transaction_approvals (
                    id TEXT PRIMARY KEY,
                    token_digest TEXT NOT NULL UNIQUE,
                    idempotency_key TEXT NOT NULL UNIQUE,
                    run_id TEXT NOT NULL REFERENCES runs(id),
                    service TEXT NOT NULL,
                    operator TEXT NOT NULL,
                    parameters TEXT NOT NULL,
                    expires_at TEXT NOT NULL,
                    result TEXT
                );
                CREATE INDEX IF NOT EXISTS transaction_approvals_expiry
                    ON transaction_approvals(expires_at) WHERE result IS NULL;
                """)
            db.executescript(CASE_SCHEMA)
            db.executescript(
                audit.AUDIT_SCHEMA.replace(" WITHOUT ROWID", "") if postgres else audit.AUDIT_SCHEMA
            )
            if postgres is None:
                begin_write(db)
                columns = {row[1] for row in db.execute("PRAGMA table_info(incidents)")}
                if "publication" not in columns:
                    db.execute(
                        "ALTER TABLE incidents ADD COLUMN publication TEXT NOT NULL DEFAULT '{}'"
                    )
            elif postgres.audit_role:
                db.execute(
                    sql.SQL("GRANT SELECT ON audit_events TO {}").format(
                        sql.Identifier(postgres.audit_role)
                    )
                )
            db.execute("DELETE FROM audit_events WHERE day < ?", (audit.cutoff(self.clock()),))

    @contextmanager
    def connection(self):
        if self.postgres is not None:
            with self.postgres.connect() as db:
                yield db
            return
        with closing(sqlite3.connect(self.path)) as db, db:
            db.execute("PRAGMA foreign_keys = ON")
            yield db

    def prune_audit(self) -> None:
        with self.connection() as db:
            begin_write(db)
            db.execute("DELETE FROM audit_events WHERE day < ?", (audit.cutoff(self.clock()),))

    def probe_readiness(self) -> None:
        with self.connection() as db:
            db.execute("SELECT id FROM runs LIMIT 1").fetchone()

    def audit_history(self, scenario_id: str, checkpoint_path: Path | None) -> audit.AuditHistory:
        with self.connection() as db:
            begin_read(db)
            return audit.history(db, checkpoint_path, scenario_id, self.clock())

    def metrics_report(
        self, window: ToolMinutes, scenario_ids: tuple[str, ...] | None
    ) -> MetricsReport:
        with self.connection() as db:
            begin_read(db)
            if scenario_ids is None:
                scenario_ids = tuple(row[0] for row in db.execute("SELECT id FROM work_cases"))
            return live_report(db, self.clock(), window, scenario_ids)

    def anomaly_report(self, scenario_id: str) -> AnomalyReport:
        with self.connection() as db:
            begin_read(db)
            return detect_anomalies(db, scenario_id, self.clock())

    def audit_run(
        self,
        db: StoreConnection,
        run: Run,
        caller: Caller | None,
        action: str,
        decision: audit.Decision,
        result: str,
        *,
        approval_id: str | None = None,
        at: datetime | None = None,
    ) -> None:
        audit.append(
            db,
            run.scenario_id,
            audit.AuditEvent(
                at=at or self.clock(),
                service=caller.service if caller else "executor",
                operator=caller.operator if caller else None,
                run_id=run.id,
                action=action,
                decision=decision,
                result=result,
                approval_id=approval_id,
                trace_id=run.trace_id,
                steps_used=len(run.steps)
                if action == "run_saved" and run.mode == "agent"
                else None,
                step_limit=run.step_limit
                if action == "run_saved" and run.mode == "agent"
                else None,
                priority=run.recommendation.priority,
                queue="Уведомления" if run.recommendation.queue == "Уведомления" else None,
                incident_id=run.incident_id,
            ),
        )

    def audit_tool(
        self,
        caller: Caller,
        proposal: ToolProposal,
        result: str,
        *,
        admitted: bool | None = None,
        observation: Observation | None = None,
    ) -> None:
        context = current.get()
        trace_id = (
            context.trace_id
            if context
            and (context.run_id, context.scenario_id) == (proposal.run_id, proposal.scenario_id)
            else None
        )
        snapshot_at = None
        snapshot_version = None
        if proposal.action == Action.STATUS and result == "ok" and observation is not None:
            snapshot_version = blake2b(
                observation.model_dump_json().encode("utf-8"),
                digest_size=16,
                person=b"queue-snapshot",
            ).hexdigest()
            if fullmatch(r"(?:[01][0-9]|2[0-3]):[0-5][0-9]", observation.observed_at):
                snapshot_at = observation.observed_at
        with self.connection() as db:
            begin_write(db)
            audit.append(
                db,
                proposal.scenario_id,
                audit.AuditEvent(
                    at=self.clock(),
                    service=caller.service,
                    operator=caller.operator,
                    run_id=proposal.run_id,
                    action="tool_call",
                    decision="allow" if result == "ok" else "deny",
                    result=result,
                    tool=proposal.action if proposal.action in SOURCE_FOR_ACTION else None,
                    trace_id=trace_id,
                    admitted=admitted,
                    snapshot_at=snapshot_at,
                    snapshot_version=snapshot_version,
                ),
            )
        if snapshot_at is not None:
            event("monitoring_snapshot", "observed", snapshot_at=snapshot_at)

    def save(
        self, run: Run, caller: Caller | None = None, *, support_export: SupportExport | None = None
    ) -> None:
        with self.connection() as db:
            begin_write(db)
            if is_work_case(run.scenario_id):
                # Итог разбора сохраняется лишь для той ревизии фактов, по которой он получен.
                self.cases.for_run(db, run.scenario_id, run.case_revision)
            if caller is not None:
                binding = db.execute(
                    "SELECT scenario_id, service, operator FROM tool_calls WHERE run_id = ? LIMIT 1",
                    (run.id,),
                ).fetchone()
                if binding is not None and binding != (
                    run.scenario_id,
                    caller.service,
                    caller.operator,
                ):
                    raise RunConflict("Прогон закреплён за другим обращением или пользователем.")
            run.approval_deadline = (
                self.clock() + self.approval_period
                if run.status == Phase.AWAITING_APPROVAL
                else None
            )
            run.support_card_available = support_export is not None
            db.execute(
                "INSERT INTO runs VALUES (?, ?, ?, ?, ?, ?)",
                (
                    run.id,
                    run.scenario_id,
                    run.mode,
                    run.status,
                    run.lifecycle.events[0].at.isoformat(),
                    run.model_dump_json(),
                ),
            )
            if support_export is not None:
                db.execute(
                    "INSERT INTO support_cards (run_id, description, customer_email) VALUES (?, ?, ?)",
                    (run.id, support_export.description, support_export.customer_email),
                )
            db.execute("DELETE FROM tool_calls WHERE run_id = ?", (run.id,))
            self.audit_run(db, run, caller, "run_saved", "record", run.status)

    def support_card(self, run_id: str, caller: Caller) -> SupportExport:
        with self.connection() as db:
            run = self.load(db, run_id)
            caller.require_case(run.scenario_id, "read_support")
            row = db.execute(
                "SELECT description, customer_email FROM support_cards WHERE run_id = ?", (run_id,)
            ).fetchone()
            if row is None:
                raise KeyError(run_id)
            return SupportExport(description=row[0], customer_email=row[1])

    def list_agent_runs(self, scenario_id: str) -> list[RunSummary]:
        with self.connection() as db:
            begin_write(db)
            awaiting = db.execute(
                "SELECT payload FROM runs WHERE scenario_id = ? AND status = ?",
                (scenario_id, Phase.AWAITING_APPROVAL),
            ).fetchall()
            now = self.clock()
            for (payload,) in awaiting:
                self.close_expired(db, Run.model_validate_json(payload), now)
            rows = db.execute(
                """SELECT id, status, started_at, payload FROM runs
                   WHERE scenario_id = ? AND mode = 'agent'
                   ORDER BY (status = 'awaiting_approval') DESC,
                            (status IN ('needs_review', 'manual_handoff')) DESC,
                            started_at DESC LIMIT 30""",
                (scenario_id,),
            ).fetchall()
        return [
            RunSummary(
                id=id_, status=status, started_at=at, threat=json.loads(payload).get("threat")
            )
            for id_, status, at, payload in rows
        ]

    def get(self, run_id: str) -> Run:
        with self.connection() as db:
            begin_write(db)
            run = self.load(db, run_id)
            self.close_expired(db, run, self.clock())
            return run

    def count_incidents(self, scenario_id: str) -> int:
        with self.connection() as db:
            return db.execute(
                "SELECT COUNT(*) FROM incidents WHERE scenario_id = ?", (scenario_id,)
            ).fetchone()[0]

    def reserve_tool_call(
        self,
        caller: Caller,
        proposal: ToolProposal,
        scope: ToolScope,
    ) -> ToolResult | None:
        binding = (proposal.scenario_id, caller.service, caller.operator)
        with self.connection() as db:
            begin_write(db)
            if is_work_case(proposal.scenario_id):
                # До допуска к чтению повторно сверяем факты рабочего обращения.
                self.cases.for_run(db, proposal.scenario_id, proposal.case_revision)
            if db.execute("SELECT 1 FROM runs WHERE id = ?", (proposal.run_id,)).fetchone():
                return ToolResult(code="run_closed", message="Разбор завершён, чтение закрыто.")
            now = datetime.now(UTC)
            cutoff = (now - timedelta(hours=1)).isoformat()
            db.execute("DELETE FROM tool_calls WHERE requested_at < ?", (cutoff,))
            calls = db.execute(
                "SELECT scenario_id, service, operator, action FROM tool_calls WHERE run_id = ?",
                (proposal.run_id,),
            ).fetchall()
            if calls and calls[0][:3] != binding:
                return ToolResult(
                    code="run_scope_mismatch",
                    message="Прогон закреплён за другим обращением или пользователем.",
                )
            limit = call_limit(scope, [row[3] for row in calls], proposal.action)
            if limit is not None:
                return ToolResult(code=limit, message=LIMIT_MESSAGES[limit])
            # Резервирование под блокировкой учитывает параллельные вызовы в лимите;
            # само чтение источника выполняется исполнителем после выхода из транзакции.
            db.execute(
                "INSERT INTO tool_calls VALUES (?, ?, ?, ?, ?, ?)",
                (proposal.run_id, *binding, proposal.action, now.isoformat()),
            )
        return None

    def check_approval(self, run: Run, caller: Caller, *, confirmed: bool) -> ApprovalDecision:
        caller.require_case(run.scenario_id, "resolve")
        if self.approval_expired(run, self.clock()):
            return self.expired_decision()
        return check_registration(
            run,
            confirmed=confirmed,
            operator=caller.operator,
            policy_path=self.policy_path,
        )

    def publication_for(self, db: StoreConnection, run: Run) -> Publication:
        scenario = SCENARIOS.get(run.scenario_id)
        if scenario is None:
            case = self.cases.for_run(db, run.scenario_id, run.case_revision)
            assert case.evidence is not None
            if self.clock() - case.evidence.snapshot_at > timedelta(minutes=5):
                raise CaseError(
                    409,
                    "stale_snapshot",
                    "Снимок очереди устарел. Обновите данные и повторите разбор.",
                )
            scenario = case.scenario()
            if scenario.monitoring.scope != "incident":
                raise CaseError(
                    409, "invalid_evidence", "Данные очереди не подтверждают массовую задержку."
                )
        return build_publication(scenario, run.recommendation.incident_fields)

    @staticmethod
    def load(db: StoreConnection, run_id: str) -> Run:
        row = db.execute("SELECT payload FROM runs WHERE id = ?", (run_id,)).fetchone()
        if row is None:
            raise KeyError(run_id)
        return Run.model_validate_json(row[0])

    def load_manual_review(
        self, db: StoreConnection, run_id: str, caller: Caller, action: str
    ) -> Run:
        run = self.load(db, run_id)
        self.require_resolution(db, run, caller, action)
        if is_work_case(run.scenario_id):
            self.cases.for_run(db, run.scenario_id, run.case_revision)
        if run.status != Phase.MANUAL_HANDOFF or not run.manual_registration_available:
            raise RunConflict(
                "Подготовка инцидента доступна после принятия обращения в ручной разбор."
            )
        return run

    def manual_target(self, run_id: str, caller: Caller) -> Run:
        with self.connection() as db:
            begin_write(db)
            return self.load_manual_review(db, run_id, caller, "manual_evidence")

    def save_manual_evidence(self, run_id: str, caller: Caller, steps: list[Step]) -> Run:
        with self.connection() as db:
            begin_write(db)
            run = self.load_manual_review(db, run_id, caller, "manual_evidence")
            run.manual_evidence = steps
            run.approval_block = None
            code = "manual_evidence_verified" if steps else "manual_evidence_unavailable"
            self.update(db, run)
            self.audit_run(db, run, caller, "manual_evidence", "record", code)
        logger.info("Ручная проверка источников прогон=%s код=%s", run_id, code)
        event("manual_evidence", code)
        return run

    def prepare_manual_draft(self, run_id: str, caller: Caller, draft: ManualDraft) -> Run:
        with self.connection() as db:
            begin_write(db)
            run = self.load_manual_review(db, run_id, caller, "manual_draft")
            candidate = run.model_copy(deep=True)
            candidate.recommendation = Recommendation(
                category="incident",
                title="Дежурный подготовил инцидент P2",
                detail="Дежурный сверил источники и указал приоритет по регламенту RB-NOTIFY-07.",
                priority=draft.priority,
                queue=INCIDENT_QUEUE,
            )
            now = self.clock()
            candidate.lifecycle.move(
                Phase.AWAITING_APPROVAL,
                "Ручной черновик передан на согласование",
                "Дежурный может проверить карточку и подтвердить регистрацию.",
                at=now,
            )
            candidate.approval_deadline = now + self.approval_period
            candidate.approval_block = None
            policy = self.check_approval(candidate, caller, confirmed=True)
            if policy.code != ApprovalCode.ALLOWED:
                self.block(db, run, policy, caller)
            if is_work_case(candidate.scenario_id):
                self.publication_for(db, candidate)
            self.record_hitl(
                db, candidate, "manual_draft_prepared", "Дежурный указал приоритет P2."
            )
            self.audit_run(db, candidate, caller, "manual_draft", "record", "manual_draft_prepared")
            return candidate

    def issue_approval(self, run_id: str, intent: ApprovalIntent, caller: Caller) -> ApprovalToken:
        with self.connection() as db:
            begin_write(db)
            run = self.load(db, run_id)
            self.require_resolution(db, run, caller, "approve_draft")
            self.deny_expired(db, run, self.clock(), caller)
            if run.status != Phase.AWAITING_APPROVAL:
                raise RunConflict("Этот прогон уже закрыт или не ожидает согласования.")
            if run.scenario_id != intent.scenario_id or run.recommendation != intent.recommendation:
                self.audit_run(db, run, caller, "approve_draft", "deny", "approval_changed")
                db.commit()
                raise TransactionRejected(
                    409,
                    "approval_changed",
                    "Черновик изменился. Проверьте его и подтвердите заново.",
                )
            policy = self.check_approval(run, caller, confirmed=True)
            event("approval_policy", policy.code, check_level="hitl")
            if policy.code != ApprovalCode.ALLOWED:
                self.block(db, run, policy, caller)
            publication = self.publication_for(db, run)
            # Токен фиксирует именно проверенные черновик и состав публикации.
            now = self.clock()
            self.deny_expired(db, run, now, caller)
            assert run.approval_deadline is not None
            grant = ApprovalToken(
                approval_id=token_hex(16),
                token=token_hex(32),
                idempotency_key=token_hex(16),
                expires_at=min(run.approval_deadline, now + timedelta(seconds=TRANSACTION_SECONDS)),
            )
            parameters = ApprovedParameters(
                scenario_id=run.scenario_id,
                recommendation=run.recommendation,
                publication=publication,
            )
            db.execute(
                "DELETE FROM transaction_approvals WHERE result IS NULL AND expires_at < ?",
                ((now - timedelta(hours=1)).isoformat(),),
            )
            db.execute(
                """INSERT INTO transaction_approvals
                   (id, token_digest, idempotency_key, run_id, service, operator, parameters, expires_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    grant.approval_id,
                    self.token_digest(grant.token),
                    grant.idempotency_key,
                    run.id,
                    caller.service,
                    caller.operator,
                    parameters.model_dump_json(),
                    grant.expires_at.isoformat(),
                ),
            )
            self.audit_run(
                db,
                run,
                caller,
                "approve_draft",
                "allow",
                "token_issued",
                approval_id=grant.approval_id,
                at=now,
            )
        logger.info(
            "Токен согласования выдан согласование=%s прогон=%s оператор=%s",
            grant.approval_id,
            run.id,
            caller.operator,
        )
        return grant

    @staticmethod
    def token_digest(token: str) -> str:
        return blake2b(token.encode("ascii"), digest_size=32).hexdigest()

    def load_approval(
        self,
        db: StoreConnection,
        run: Run,
        caller: Caller,
        token: str | None,
        idempotency_key: str | None,
    ) -> tuple[str, ApprovedParameters, datetime, str | None]:
        if token is None or idempotency_key is None:
            raise TransactionRejected(
                409,
                "transaction_token_required",
                "Подтвердите черновик для получения токена операции.",
            )
        row = db.execute(
            """SELECT id, parameters, expires_at, result FROM transaction_approvals
               WHERE token_digest = ? AND idempotency_key = ?
                 AND run_id = ? AND service = ? AND operator = ?""",
            (self.token_digest(token), idempotency_key, run.id, caller.service, caller.operator),
        ).fetchone()
        if row is None:
            raise TransactionRejected(
                403, "transaction_token_invalid", "Согласование не подходит для этого запроса."
            )
        approval_id, parameters, expiry, result = row
        return (
            approval_id,
            ApprovedParameters.model_validate_json(parameters),
            datetime.fromisoformat(expiry),
            result,
        )

    def validate_approval_time(
        self,
        db: StoreConnection,
        run: Run,
        expires_at: datetime,
        now: datetime,
        caller: Caller,
        approval_id: str,
    ) -> None:
        self.deny_expired(db, run, now, caller)
        if now >= expires_at:
            self.audit_run(
                db,
                run,
                caller,
                "register_incident",
                "deny",
                "transaction_token_expired",
                approval_id=approval_id,
                at=now,
            )
            db.commit()
            raise TransactionRejected(
                409,
                "transaction_token_expired",
                "Срок токена операции истёк. Подтвердите черновик заново.",
            )

    def invalidate_approval(
        self, db: StoreConnection, run: Run, approval_id: str, caller: Caller
    ) -> Never:
        db.execute("DELETE FROM transaction_approvals WHERE id = ?", (approval_id,))
        self.audit_run(
            db,
            run,
            caller,
            "register_incident",
            "deny",
            "approval_changed",
            approval_id=approval_id,
        )
        db.commit()
        logger.warning(
            "Подтверждённые параметры изменились согласование=%s прогон=%s", approval_id, run.id
        )
        raise TransactionRejected(
            409, "approval_changed", "Черновик изменился. Проверьте его и подтвердите заново."
        )

    def resolve(
        self,
        run_id: str,
        decision: RunDecision,
        caller: Caller,
        *,
        transaction_token: str | None = None,
        idempotency_key: str | None = None,
    ) -> Run:
        with self.connection() as db:
            begin_write(db)
            run = self.load(db, run_id)
            self.require_resolution(
                db, run, caller, "register_incident" if decision == "approve" else decision
            )
            if decision != "approve" and (
                transaction_token is not None or idempotency_key is not None
            ):
                raise TransactionRejected(
                    409,
                    "transaction_action_invalid",
                    "Этот токен разрешает только регистрацию инцидента.",
                )
            if decision == "take_over":
                if run.status == Phase.MANUAL_HANDOFF:
                    return run
                if run.status != Phase.NEEDS_REVIEW or run.mode != "agent":
                    raise RunConflict("Прогон не ожидает передачи в ручной разбор.")
                run.lifecycle.move(
                    Phase.MANUAL_HANDOFF,
                    "Дежурный принял обращение",
                    f"Назначен ручной разбор. Оператор: {caller.operator}.",
                )
                self.record_hitl(
                    db, run, "taken_over", "Дежурный принял обращение в ручной разбор."
                )
                self.audit_run(db, run, caller, "take_over", "allow", "manual_handoff")
                return run
            if decision in {"complete_manual", "fail_manual"}:
                return self.finish_manual(db, run, caller, succeeded=decision == "complete_manual")
            if decision == "approve":
                try:
                    approval_id, parameters, expires_at, result = self.load_approval(
                        db, run, caller, transaction_token, idempotency_key
                    )
                except TransactionRejected as error:
                    self.audit_run(db, run, caller, "register_incident", "deny", error.code)
                    db.commit()
                    raise
                if result is not None:
                    # Повтор того же согласования возвращает сохранённый результат без новой записи.
                    self.audit_run(
                        db,
                        run,
                        caller,
                        "register_incident",
                        "replay",
                        "receipt_returned",
                        approval_id=approval_id,
                    )
                    logger.info(
                        "Возвращён результат повтора согласование=%s прогон=%s", approval_id, run.id
                    )
                    return Run.model_validate_json(result)
                self.validate_approval_time(db, run, expires_at, self.clock(), caller, approval_id)
            if decision == "reject" and run.status == Phase.REJECTED:
                return run
            self.deny_expired(db, run, self.clock(), caller)
            if run.status != Phase.AWAITING_APPROVAL:
                raise RunConflict("Этот прогон уже закрыт или не ожидает согласования.")
            if decision == "approve":
                if (
                    run.scenario_id != parameters.scenario_id
                    or run.recommendation != parameters.recommendation
                ):
                    self.invalidate_approval(db, run, approval_id, caller)
                policy = self.check_approval(run, caller, confirmed=True)
                event("approval_policy", policy.code, check_level="hitl")
                if policy.code != ApprovalCode.ALLOWED:
                    self.block(db, run, policy, caller, approval_id=approval_id)
                logger.info("Полномочия подтверждены прогон=%s код=%s", run.id, policy.code)
            recommendation = run.recommendation
            if decision == "approve":
                publication = self.publication_for(db, run)
                # Перед записью ещё раз сверяем состав публикации и срок токена;
                # все проверки и INSERT выполняются в одной транзакции записи.
                if publication != parameters.publication:
                    self.invalidate_approval(db, run, approval_id, caller)
                write_time = self.clock()
                self.validate_approval_time(db, run, expires_at, write_time, caller, approval_id)
            else:
                self.deny_expired(db, run, self.clock(), caller)
            lifecycle = run.lifecycle
            lifecycle.move(
                Phase.OBSERVE,
                f"Получено решение дежурного ({caller.operator})",
                "Подтвердить черновик" if decision == "approve" else "Отклонить черновик",
            )
            if decision == "approve":
                lifecycle.move(
                    Phase.REASON,
                    "Подтверждены параметры и полномочия",
                    policy.message,
                )
                # Уникальность scenario_id закрывает гонку регистрации одного обращения.
                cursor = db.execute(
                    """INSERT INTO incidents (run_id, scenario_id, priority, queue, created_at, publication)
                       VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (scenario_id) DO NOTHING""",
                    (
                        run.id,
                        run.scenario_id,
                        recommendation.priority,
                        recommendation.queue,
                        write_time.isoformat(),
                        publication.model_dump_json(exclude_none=True),
                    ),
                )
                incident = db.execute(
                    "SELECT id, publication FROM incidents WHERE scenario_id = ?",
                    (run.scenario_id,),
                ).fetchone()
                assert incident is not None
                run.incident_id = f"INC-{3070 + incident[0]}"
                run.publication = Publication.model_validate_json(incident[1])
                title = (
                    "Инцидент зарегистрирован"
                    if cursor.rowcount
                    else "Найден существующий инцидент"
                )
                lifecycle.move(Phase.ACT, title, run.incident_id)
                if run.manual_registration_available:
                    lifecycle.move(
                        Phase.MANUAL_COMPLETED, "Ручной разбор завершён", run.incident_id
                    )
                else:
                    lifecycle.move(Phase.COMPLETED, "Разбор завершён", run.incident_id)
            else:
                lifecycle.move(Phase.REASON, "Черновик отклонён", "Дежурный отказал в регистрации.")
                lifecycle.move(Phase.ACT, "Согласование закрыто", "Инцидент не зарегистрирован.")
                lifecycle.move(Phase.REJECTED, "Разбор закрыт дежурным", recommendation.title)
            self.record_hitl(
                db,
                run,
                "approved" if decision == "approve" else "rejected",
                "Дежурный подтвердил регистрацию."
                if decision == "approve"
                else "Дежурный отклонил черновик.",
            )
            if decision == "approve":
                db.execute(
                    "UPDATE transaction_approvals SET result = ? WHERE id = ?",
                    (run.model_dump_json(), approval_id),
                )
                self.audit_run(
                    db,
                    run,
                    caller,
                    "register_incident",
                    "allow",
                    "created" if cursor.rowcount else "existing_incident",
                    approval_id=approval_id,
                    at=write_time,
                )
            else:
                self.audit_run(db, run, caller, "reject_draft", "deny", "rejected")
        logger.info("Прогон %s состояние=%s инцидент=%s", run.id, run.status, run.incident_id)
        if decision == "approve":
            logger.info("Токен операции погашен согласование=%s прогон=%s", approval_id, run.id)
            event("registration", "created" if cursor.rowcount else "existing_incident")
        return run

    def finish_manual(
        self, db: StoreConnection, run: Run, caller: Caller, *, succeeded: bool
    ) -> Run:
        phase = Phase.MANUAL_COMPLETED if succeeded else Phase.FAILED
        if run.status == phase:
            return run
        if run.status != Phase.MANUAL_HANDOFF:
            raise RunConflict("Обращение должно быть принято дежурным в ручной разбор.")
        now = self.clock()
        title = "Ручной разбор завершён" if succeeded else "Обращение закрыто с ошибкой"
        detail = f"Итог ручного разбора зафиксировал оператор {caller.operator}."
        run.lifecycle.move(phase, title, detail, at=now)
        self.record_hitl(db, run, phase, detail)
        self.audit_run(db, run, caller, "finish_manual", "record", phase, at=now)
        return run

    def require_resolution(
        self, db: StoreConnection, run: Run, caller: Caller, action: str
    ) -> None:
        caller.require_case(run.scenario_id, "read")
        try:
            caller.require_case(run.scenario_id, "resolve")
        except HTTPException as error:
            code = (error.headers or {}).get("X-Policy-Code", "operation_forbidden")
            self.audit_run(db, run, caller, action, "deny", code)
            db.commit()
            raise

    @staticmethod
    def update(db: StoreConnection, run: Run) -> None:
        db.execute(
            "UPDATE runs SET status = ?, payload = ? WHERE id = ?",
            (run.status, run.model_dump_json(), run.id),
        )

    def block(
        self,
        db: StoreConnection,
        run: Run,
        policy: ApprovalDecision,
        caller: Caller,
        *,
        approval_id: str | None = None,
    ) -> Never:
        now = self.clock()
        if policy.code == ApprovalCode.APPROVAL_EXPIRED:
            self.expire(db, run, now, caller)
            db.commit()
            assert run.approval_block is not None
            raise ApprovalRejected(run.approval_block)
        block = ApprovalBlock(code=policy.code, message=policy.message, at=now)
        run.approval_block = block
        self.update(db, run)
        self.audit_run(
            db,
            run,
            caller,
            "register_incident" if approval_id else "approve_draft",
            "deny",
            policy.code,
            approval_id=approval_id,
            at=now,
        )
        db.commit()
        logger.warning("Регистрация заблокирована прогон=%s код=%s", run.id, block.code)
        raise ApprovalRejected(block)

    @staticmethod
    def approval_expired(run: Run, now: datetime) -> bool:
        return run.status == Phase.AWAITING_APPROVAL and (
            run.approval_deadline is None or now >= run.approval_deadline
        )

    @staticmethod
    def expired_decision() -> ApprovalDecision:
        return ApprovalDecision(
            code=ApprovalCode.APPROVAL_EXPIRED,
            message="Срок согласования истёк. Обновите данные и запустите новый разбор.",
        )

    def close_expired(
        self, db: StoreConnection, run: Run, now: datetime, caller: Caller | None = None
    ) -> None:
        if self.approval_expired(run, now):
            self.expire(db, run, now, caller)

    def expire(
        self, db: StoreConnection, run: Run, now: datetime, caller: Caller | None = None
    ) -> None:
        reason = self.expired_decision()
        run.approval_block = ApprovalBlock(code=reason.code, message=reason.message, at=now)
        run.lifecycle.move(
            Phase.APPROVAL_EXPIRED, "Срок согласования истёк", reason.message, at=now
        )
        self.record_hitl(db, run, reason.code, reason.message)
        self.audit_run(db, run, caller, "expire_approval", "deny", reason.code, at=now)

    def deny_expired(
        self, db: StoreConnection, run: Run, now: datetime, caller: Caller | None = None
    ) -> None:
        self.close_expired(db, run, now, caller)
        if run.status == Phase.APPROVAL_EXPIRED:
            assert run.approval_block is not None
            db.commit()
            raise ApprovalRejected(run.approval_block)

    def record_hitl(self, db: StoreConnection, run: Run, code: str, detail: str) -> None:
        run.shield_checks.append(ShieldCheck(level="hitl", code=code, detail=detail))
        self.update(db, run)
        logger.info("Shield прогон=%s уровень=hitl код=%s", run.id, code)
